def stacked(*lines):
    return r'\shortstack{' + r'\\'.join(lines) + '}'


def network_notation(tex):
    """Обозначения п. 6.7.11 теории: lambda_0 и U, не Lambda и u."""
    tex=tex.replace(r'\Lambda_{\text{точн}}',r'\lambda_{0,\text{точн}}')
    tex=tex.replace(r'\Lambda',r'\lambda_0')
    tex=tex.replace(r'\lambda_{\text{пред}}',r'\lambda_{0,\text{пред}}')
    tex=tex.replace(r'\lambda_M',r'\lambda_{0,M}')
    for law in ['E_2','H_2']:
        tex=tex.replace(r'\lambda_{'+law+'}',r'\lambda_{0,'+law+'}')
    tex=re.sub(r'\\lambda(?![_A-Za-z])',lambda m:r'\lambda_0',tex)
    def times(match):
        s=match.group()
        return re.sub(r'(?<![A-Za-z\\])([wu])(?![A-Za-z]|_(?:j|[123])|_\{(?:j|[123])\})',lambda m:m[1].upper(),s)
    tex=re.sub(r'\\\([\s\S]*?\\\)',times,tex)
    tex=re.sub(r'\\begin\{(?:equation|gather)\}[\s\S]*?\\end\{(?:equation|gather)\}',times,tex)
    return tex


def table(headers,rows,width=None):
    text='\\begin{center}\\small\\renewcommand{\\arraystretch}{1.3}\n'
    if width:text+=f'\\resizebox{{{width}}}{{!}}{{'
    text+='\\begin{tabular}{|'+'|'.join(['l']+['c']*(len(headers)-1))+'|}\\hline\n'
    text+=' & '.join(headers)+r'\\\hline'+'\n'
    for row in rows:text+=' & '.join(map(str,row))+r'\\\hline'+'\n'
    text+='\\end{tabular}'+('}' if width else '')+'\\end{center}\n'
    return text


